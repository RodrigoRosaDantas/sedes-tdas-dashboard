import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=file=>fs.readFileSync(file,'utf8');
const index=read('index.html'),postExam=read('assets/integration/post-exam-home.js'),priorities=read('assets/integration/daily-priorities.js'),reviewEngine=read('assets/integration/review-engine.js'),reviews=read('assets/integration/module-reviews.js'),redactions=read('assets/redactions.js'),redactionsPage=read('redacoes/index.html'),player=read('assets/integration/module-player.js'),audit=read('auditoria/index.html'),unlinked=read('assets/integration/audit-unlinked-errors.js'),auditData=JSON.parse(read('data/audit.json')),platform=JSON.parse(read('data/platform-version.json')),packageData=JSON.parse(read('package.json'));

assert.ok(index.includes('post-exam-home.js?v=2.0.0'),'Home deve usar renderer pós-prova nativo.');
assert.ok(!index.includes('home-dashboard-pro-2026.js')&&!index.includes('dashboard-pro-2026.css'),'Central diária e CSS de reta final não podem ser dependências ativas da Home.');
assert.ok(!index.includes('home-command-center.js')&&!index.includes('command-center.css'));
assert.ok(!index.includes('SEDES/DF · v26.2'));
assert.ok(index.includes('data-post-exam-home="2"'),'Home deve declarar contrato pós-prova v2.');
assert.ok(postExam.includes("setupShell('home'"));
assert.ok(postExam.includes("loadJSON('data/home.json')"));
assert.ok(postExam.includes("loadJSON('data/platform-version.json')"));
assert.ok(postExam.includes('O ciclo terminou. Agora é acompanhar o concurso.'));
assert.ok(postExam.includes('Gabarito preliminar'));
assert.ok(postExam.includes('FOTOGRAFIA FINAL'));
assert.ok(postExam.includes('ARQUIVO DO CICLO'));
assert.ok(postExam.includes('Última sincronização'));
assert.ok(postExam.includes('platform.sourceCommit'));
assert.ok(postExam.includes('Sem data oficial cadastrada. O site não inventa prazo.'));
assert.ok(!postExam.includes('Central de execução'));
assert.ok(!postExam.includes('readSessionDraft'));
assert.ok(!postExam.includes('selectPrimaryAction'));
assert.ok(!postExam.includes('home.overdue'));
assert.ok(!postExam.includes('buildOfficialCycleTasks'));
assert.ok(!postExam.includes('Continuar estudo'));

// A infraestrutura histórica de execução continua íntegra, mas não preempta mais a Home pós-prova.
assert.ok(priorities.includes('Continuar de onde parei'));
assert.ok(priorities.includes("stage:'overdue'"));
assert.ok(priorities.includes('Retomar PE atrasado'));
assert.ok(priorities.includes("id:'redaction'"));
assert.ok(priorities.includes('pendingRedaction'));
assert.ok(priorities.includes('official-reviews'));
assert.ok(priorities.includes('Prioridade de revisão externa'));
assert.ok(!priorities.includes('resolver/?review='),'Prioridades históricas não podem iniciar revisão interna.');
assert.ok(!priorities.includes("stage:'review'"),'Revisão local não pode preemptar o fluxo diário legado.');
assert.ok(!priorities.includes('localStorage.setItem')&&!priorities.includes('fetch('));
assert.ok(reviewEngine.includes("MASTERED:'mastered'"));
assert.ok(reviewEngine.includes('reviewPriorityScore'));
assert.ok(reviews.includes("dataset.reviewMode='priorities-only'"));
assert.ok(reviews.includes('O TDAS não executa mais a revisão'));
assert.ok(!reviews.includes('Iniciar revisão prioritária'));
assert.ok(redactionsPage.includes(`assets/redactions.js?v=${packageData.version}`),'A página deve carregar o módulo de redações com a versão consolidada.');
assert.ok(/(?:params|currentParams)\.get\('rd'\)/.test(redactions),'O Dashboard Discursivo deve aceitar foco por RD na URL.');
assert.ok(/(?:params|currentParams)\.get\('pe'\)/.test(redactions),'O Dashboard Discursivo deve aceitar foco por PE na URL.');
assert.ok(redactions.includes('data-focused-redaction'));
assert.ok(redactions.includes('history.replaceState'),'Os filtros do Banco Discursivo devem permanecer refletidos na URL.');
assert.ok(player.includes('matchingSessionDraft'));
assert.ok(player.includes('writeSessionDraft'));
assert.ok(player.includes('clearSessionDraft'));
assert.ok(!player.includes('data-review-outcome')&&!player.includes('Correção da revisão')&&!player.includes("mode:'review'"),'Player preservado não pode manter execução interna de revisão.');
assert.ok(player.includes('não foi salvo como histórico pessoal'),'Resultado concluído precisa declarar o contrato efêmero.');
assert.ok(audit.includes('audit-unlinked-errors.js?v=1.0.0'));
assert.ok(unlinked.includes("section.id='erros-sem-origem'"));
assert.ok(unlinked.includes('items.length'));
assert.ok(unlinked.includes('Nenhuma origem foi presumida pelo site'));
const missing=(auditData.quality||[]).filter(item=>item.title==='Registro incompleto no Caderno de Erros'&&/Origem \/ Dia ID/.test(item.detail||''));
assert.ok(Array.isArray(missing));
assert.ok(!unlinked.includes('setItem(')&&!unlinked.includes('writeback'));
assert.ok(!unlinked.includes('12 pendentes'));
assert.equal(platform.peId,JSON.parse(read('data/integration/question-catalog.json')).peId);
assert.ok(!Number.isNaN(Date.parse(platform.syncAt)),'Timestamp da última sincronização inválido.');
console.log(`Pós-prova validado: Home sem central diária, infraestrutura histórica preservada, última sincronização ${platform.syncAt}, publicação ${platform.publicationId} e ${missing.length} origens pendentes sem inferência ou writeback.`);
