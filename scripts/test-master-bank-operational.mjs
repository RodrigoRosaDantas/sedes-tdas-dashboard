import assert from 'node:assert/strict';
import fs from 'node:fs';

const workflow=fs.readFileSync('.github/workflows/notion-sync.yml','utf8');
const preserve=fs.readFileSync('scripts/preserve-v27-pwa.mjs','utf8');
const bank=fs.readFileSync('assets/integration/question-bank.js','utf8');
const review=fs.readFileSync('assets/integration/review-catalog-bridge.js','utf8');
const player=fs.readFileSync('assets/integration/question-bank-player.js','utf8');
const bootstrap=fs.readFileSync('assets/integration/resolver-bootstrap.js','utf8');
const masterUi=fs.readFileSync('assets/integration/master-bank-ui.js','utf8');
const css=fs.readFileSync('assets/v27.css','utf8');
const syncPos=workflow.indexOf('node scripts/sync-tdas-master-question-bank.mjs');
const preservePos=workflow.indexOf('node scripts/preserve-v27-pwa.mjs');
const validatePos=workflow.indexOf('node scripts/validate-master-question-bank.mjs');
const gatePos=workflow.indexOf('npm run check');
assert.ok(syncPos>=0,'A sincronização operacional deve materializar o Banco Mestre.');
assert.ok(preservePos>syncPos,'O PWA deve ser preservado depois da materialização do Banco Mestre.');
assert.ok(validatePos>preservePos,'O snapshot materializado deve ser validado depois do PWA.');
assert.ok(gatePos>validatePos,'O gate integral deve rodar depois da validação do Banco Mestre.');
for(const dependency of ['scripts/sync-tdas-master-question-bank.mjs','scripts/validate-master-question-bank.mjs','scripts/test-master-question-bank.mjs'])assert.ok(workflow.includes(`- '${dependency}'`),`Workflow não reage a ${dependency}.`);
assert.match(workflow,/git add -A data pe materias sw\.js/,'Snapshot e chave separados precisam participar da publicação atômica.');
const optionalMatch=preserve.match(/const OPTIONAL_DATA=(\[[^;]*\]);/);
assert.ok(optionalMatch,'Lista OPTIONAL_DATA ausente no preservador PWA.');
const optionalData=JSON.parse(optionalMatch[1].replace(/'/g,'"'));
assert.ok(optionalData.includes('data/integration/master-question-bank.json'),'Catálogo público mestre deve ser preservado no PWA.');
assert.ok(optionalData.every(item=>!String(item).includes('question-keys/')),'A chave do Banco Mestre não pode ser adicionada ao PWA.');
assert.match(preserve,/assets\/integration\/master-bank-ui\.js/,'Resumo visual do Banco Mestre deve ser preservado no PWA.');
assert.match(bank,/master-question-bank\.json/,'Runtime do Banco deve carregar o snapshot mestre local.');
assert.match(bank,/sourceKind:'master-bank'/,'Runtime deve identificar questões do Banco Mestre.');
assert.match(review,/loadMasterQuestionBank/,'Revisões devem recuperar questões do Banco Mestre.');
assert.match(review,/mode:'master-review'/,'Revisões mestre devem usar catálogo sintético isolado.');
assert.match(bootstrap,/master-bank-ui\.js\?v=1\.0\.0/,'Modo Banco deve carregar o resumo visual do acervo.');
assert.match(masterUi,/data-master-bank-summary/,'Resumo visual deve ter marcador estável.');
assert.match(masterUi,/snapshot\.questionCount/,'Resumo visual deve usar a quantidade publicada, não um número fixo.');
assert.match(masterUi,/snapshot\.materialCount/,'Resumo visual deve usar a quantidade real de materiais.');
for(const token of ['data-bank-material','data-bank-banca','data-bank-tipo','data-bank-size="10"','data-bank-size="20"','data-bank-size="30"','data-bank-size="50"','data-bank-size="all"'])assert.ok(player.includes(token),`Construtor do Banco sem ${token}.`);
assert.match(player,/function syncFilterOptions\(/,'Filtros do Banco não estão encadeados.');
assert.match(player,/facetValues\(next,definition\)/,'Opções de filtro não são recalculadas pelo recorte atual.');
assert.match(player,/filterBankQuestions\(state\.allQuestions,filters\)/,'Contagem e prévia não são recalculadas em tempo real.');
assert.match(player,/question\.materialName/,'Prévia e sessão devem exibir o material de origem quando disponível.');
assert.match(css,/\.bank-size-presets/,'Atalhos de quantidade não possuem layout dedicado.');
assert.match(css,/\.bank-search-wide/,'Busca do Banco não possui layout responsivo dedicado.');
const finish=player.indexOf('async function finishSession');
const keyLoad=player.indexOf('loadMergedBankKey',finish);
assert.ok(finish>=0&&keyLoad>finish,'O player do Banco deve continuar buscando a correção somente no fechamento.');
console.log('Operação do Banco Mestre blindada: sync, filtros encadeados, tamanhos rápidos, PWA público, chave fora do precache e revisão recuperável.');